// Builds a test shoot on disk for trying the real folder picker.
// Usage: node scripts/make-test-folder.mjs "<output folder>"
//
// Each frame is a crop that pans across a source picture, so scrubbing a burst looks like motion.
// Uses a drawn surf scene, or your own photo with SOURCE=path/to/photo.jpg.
import sharp from 'sharp';
import { execFileSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync, utimesSync, existsSync, readdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { sourceImage } from './source-image.mjs';

const OUT = resolve(process.argv[2] ?? 'test-shoot');
if (existsSync(OUT) && readdirSync(OUT).length && !existsSync(join(OUT, 'README.txt'))) {
  console.error(`${OUT} exists and is not a test shoot made by this script; refusing to overwrite.`);
  process.exit(1);
}
rmSync(OUT, { recursive: true, force: true });

const { input: HERO, width: SW, height: SH } = await sourceImage();
const pad = (n, l = 2) => String(n).padStart(l, '0');
const exifDate = (d) =>
  `${d.getFullYear()}:${pad(d.getMonth() + 1)}:${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
const at = (h, m, s, ms = 0) => new Date(2026, 10, 14, h, m, s, ms);
const touch = (path, t) => utimesSync(path, t, t);

// [folder, start, frames, fps, hue, options]
const bursts = [
  ['Morning', at(10, 41, 52, 120), 18, 10, 0],
  ['Morning', at(10, 41, 58, 400), 1, 1, 30], // single frame
  ['Morning', at(10, 42, 19, 0), 24, 12, 200],
  ['Morning', at(10, 42, 36, 500), 40, 20, 90], // long fast burst: good for scrubbing
  // Two bursts 0.9 s apart: one burst at a 1.0 s gap, two at 0.75 s.
  ['Morning/Jump line', at(10, 55, 0, 0), 10, 10, 330],
  ['Morning/Jump line', at(10, 55, 1, 800), 10, 10, 60],
  // Two bursts 1.2 s apart: two bursts at 1.0 s, one at 1.5 s.
  ['Morning/Jump line', at(10, 56, 0, 0), 8, 8, 160],
  ['Morning/Jump line', at(10, 56, 2, 75), 8, 8, 280],
  ['Afternoon', at(14, 5, 3, 0), 12, 8, 300],
  ['Afternoon/Lift 2', at(14, 20, 11, 0), 16, 10, 240, { rawTwinAt: 5 }],
  // Same time as the burst above but a different folder (second camera): stays separate.
  ['Afternoon/Lift 2/Second body', at(14, 20, 11, 50), 6, 5, 20, { prefix: 'DSC_' }],
  ['Afternoon/Lift 2', at(14, 31, 40, 0), 14, 10, 120, { noExif: true }], // falls back to file dates
];

let n = 845;
let photos = 0;
for (const [folder, start, count, fps, hue, opt = {}] of bursts) {
  mkdirSync(join(OUT, folder), { recursive: true });
  for (let i = 0; i < count; i++) {
    const t = new Date(start.getTime() + Math.round((i * 1000) / fps));
    const p = count > 1 ? i / (count - 1) : 0.5;
    const cw = Math.round(SW * 0.62), ch = Math.round(cw / 1.5);
    const left = Math.round((SW - cw) * p);
    const top = Math.round((SH - ch) * (0.5 - 0.35 * Math.sin(p * Math.PI)));
    const base = `${opt.prefix ?? 'IMG_'}${pad(n++, 4)}`;
    let img = sharp(HERO)
      .extract({ left, top, width: cw, height: ch })
      .resize(1800, 1200)
      .modulate({ hue, brightness: 0.85 + 0.3 * Math.sin(p * Math.PI) });
    if (!opt.noExif) {
      img = img.withExif({
        IFD0: { Make: 'Test', Model: 'Burst Cam' },
        IFD2: { DateTimeOriginal: exifDate(t), SubSecTimeOriginal: pad(t.getMilliseconds(), 3) },
      });
    }
    const path = join(OUT, folder, `${base}.JPG`);
    await img.jpeg({ quality: 80 }).toFile(path);
    touch(path, t);
    photos++;
    if (opt.rawTwinAt === i) {
      // Stand-in RAW twin: should be attached to the JPG ("+RAW"), not shown as a second frame.
      const raw = join(OUT, folder, `${base}.CR2`);
      writeFileSync(raw, Buffer.alloc(1024));
      touch(raw, t);
    }
  }
}

// Videos: never grouped, each its own entry.
for (const [folder, name, t, src] of [
  ['Morning', 'MVI_0901.MP4', at(11, 15, 0), 'testsrc2=size=960x540:rate=25:duration=3'],
  ['Afternoon', 'MVI_0957.MOV', at(14, 10, 30), 'smptebars=size=960x540:rate=25:duration=2'],
]) {
  const path = join(OUT, folder, name);
  execFileSync('ffmpeg', ['-loglevel', 'error', '-f', 'lavfi', '-i', src, '-pix_fmt', 'yuv420p', '-c:v', 'libx264', '-y', path]);
  touch(path, t);
}

// Files the scan should skip.
writeFileSync(join(OUT, '.DS_Store'), '');
writeFileSync(join(OUT, 'Morning', '._IMG_0845.JPG'), 'AppleDouble junk');
writeFileSync(join(OUT, 'Morning', 'IMG_0845.xmp'), '<x:xmpmeta/>');
writeFileSync(join(OUT, 'Afternoon', 'notes.txt'), 'not media');

writeFileSync(
  join(OUT, 'README.txt'),
  `Burst test shoot (generated by scripts/make-test-folder.mjs)

${photos} photos and 2 videos across ${new Set(bursts.map((b) => b[0])).size} folders.

What to expect at the default 1.0 s gap: 11 bursts and 2 videos.
- B05 + B06 are 0.9 s apart: one burst at 1.0 s, two at 0.75 s or less.
- B07 + B08 are 1.2 s apart: two bursts at 1.0 s, one at 1.5 s or more.
- "Second body" overlaps Lift 2 in time but is a different folder, so it stays separate.
- One Lift 2 frame has a .CR2 twin: it shows "+RAW" and is not counted twice.
- The last Lift 2 burst has no EXIF: it uses file dates ("file date" under the name).
- .DS_Store, ._ files, .xmp and .txt are ignored.
`,
);
console.log(`Wrote ${photos} photos + 2 videos to ${OUT}`);
